/**
 * ============================================================================
 *  INIT ADMIN PASSWORD — one-time setup script
 * ============================================================================
 *
 * Purpose:
 *   Hashes a plaintext password with bcrypt and stores the hash in the
 *   database Setting table (key = "admin_password_hash").
 *
 *   The plaintext password is NEVER stored anywhere. Only the bcrypt hash
 *   is persisted.
 *
 * Usage:
 *   # Option A — interactive (prompts for password, hidden input)
 *   bun run scripts/init-admin-password.ts
 *
 *   # Option B — via env var (for CI / automated deploys)
 *   ADMIN_INITIAL_PASSWORD="yourStrongPassword" bun run scripts/init-admin-password.ts
 *
 *   # Option C — via CLI argument (NOT recommended — visible in shell history)
 *   bun run scripts/init-admin-password.ts "yourStrongPassword"
 *
 * Security:
 *   - Password is read from stdin (hidden) or env var — never logged.
 *   - Only the bcrypt hash is written to the database.
 *   - If a password hash already exists, the script asks for confirmation
 *     before overwriting.
 *
 * Requirements:
 *   - DATABASE_URL must be set in .env (PostgreSQL connection string)
 *   - Run `bun run db:push` first to create the Setting table
 * ============================================================================
 */

import bcrypt from "bcryptjs";
import readline from "readline";

// Load .env
const { config } = await import("dotenv");
config();

const DATABASE_URL = process.env.DATABASE_URL;

if (!DATABASE_URL) {
  console.error("\n[ERROR] DATABASE_URL is not set.");
  console.error("        Add it to your .env file, e.g.:");
  console.error('        DATABASE_URL="postgresql://user:pass@host/db?sslmode=require"');
  process.exit(1);
}

// Dynamic import of Prisma client (already generated by postinstall)
const { PrismaClient } = await import("@prisma/client");
const db = new PrismaClient();

// ---------------------------------------------------------------------------
// Helper: read password from stdin without echoing it
// ---------------------------------------------------------------------------
function readPasswordHidden(prompt: string): Promise<string> {
  return new Promise((resolve) => {
    const rl = readline.createInterface({
      input: process.stdin,
      output: process.stdout,
      terminal: true,
    });

    // Mute output while typing (basic — works on most terminals)
    const onData = (char: Buffer) => {
      const c = char.toString();
      if (c === "\r" || c === "\n") {
        process.stdout.write("\n");
      } else if (c === "\u0003") {
        // Ctrl+C
        process.exit(0);
      } else {
        // Print asterisk to mask input
        process.stdout.write("*");
      }
    };
    process.stdin.on("data", onData);

    rl.question(prompt, (answer) => {
      process.stdin.removeListener("data", onData);
      rl.close();
      resolve(answer);
    });
  });
}

// ---------------------------------------------------------------------------
// Main
// ---------------------------------------------------------------------------
async function main() {
  console.log("\n========================================");
  console.log("  Admin Password Initialization Script");
  console.log("========================================\n");

  // 1. Get the plaintext password from env var, CLI arg, or interactive prompt
  let plaintextPassword =
    process.env.ADMIN_INITIAL_PASSWORD || process.argv[2] || "";

  if (!plaintextPassword) {
    console.log("No ADMIN_INITIAL_PASSWORD env var found.");
    console.log("Please enter a new admin password (input hidden):\n");
    plaintextPassword = await readPasswordHidden("Password: ");

    if (!plaintextPassword) {
      console.error("\n[ERROR] No password entered. Exiting.");
      process.exit(1);
    }

    // Confirm
    const confirm = await readPasswordHidden("Confirm password: ");
    if (confirm !== plaintextPassword) {
      console.error("\n[ERROR] Passwords do not match. Exiting.");
      process.exit(1);
    }
  }

  // 2. Validate password strength
  if (plaintextPassword.length < 6) {
    console.error("\n[ERROR] Password must be at least 6 characters long.");
    process.exit(1);
  }

  // 3. Check if a password hash already exists
  const existing = await db.setting.findUnique({
    where: { key: "admin_password_hash" },
  });

  if (existing) {
    console.log("\n[WARNING] An admin password is already set in the database.");
    console.log("          Overwriting will invalidate the current password.\n");

    // If running non-interactively (env var), refuse to overwrite without explicit consent
    if (process.env.ADMIN_INITIAL_PASSWORD && !process.argv.includes("--force")) {
      console.error("[ERROR] Refusing to overwrite existing password in non-interactive mode.");
      console.error("        To force overwrite, add the --force flag.");
      process.exit(1);
    }

    if (!process.env.ADMIN_INITIAL_PASSWORD) {
      const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
      const answer: string = await new Promise((resolve) =>
        rl.question("Overwrite? (yes/no): ", (a) => {
          rl.close();
          resolve(a.toLowerCase());
        })
      );
      if (answer !== "yes" && answer !== "y") {
        console.log("\nAborted. Existing password unchanged.");
        process.exit(0);
      }
    }
  }

  // 4. Hash the password with bcrypt (12 salt rounds)
  console.log("\nHashing password with bcrypt (12 salt rounds)...");
  const salt = await bcrypt.genSalt(12);
  const hash = await bcrypt.hash(plaintextPassword, salt);

  // 5. Store the hash in the database (upsert)
  await db.setting.upsert({
    where: { key: "admin_password_hash" },
    update: { value: hash },
    create: { key: "admin_password_hash", value: hash },
  });

  console.log("\n========================================");
  console.log("  SUCCESS — admin password set!");
  console.log("========================================\n");
  console.log("Details:");
  console.log("  - Stored as: bcrypt hash (12 salt rounds)");
  console.log("  - DB key:    admin_password_hash");
  console.log("  - Hash preview: " + hash.substring(0, 20) + "...");
  console.log("\nThe plaintext password is NOT stored anywhere.");
  console.log("You can now log in to the admin panel at /admin\n");

  // 6. Print a generated strong password if user didn't provide one
  //    (useful for first-time setup)
  if (!process.env.ADMIN_INITIAL_PASSWORD && !process.argv[2]) {
    console.log("TIP: To generate a random strong password, run:");
    console.log("  openssl rand -base64 18\n");
  }
}

main()
  .catch((err) => {
    console.error("\n[FATAL]", err);
    process.exit(1);
  })
  .finally(async () => {
    await db.$disconnect();
  });
